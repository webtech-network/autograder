#!/usr/bin/env python3
"""Generate or check docs/reference/ from the evaluator and definition contracts.

``evaluators.md`` renders ``describe_templates()`` (the discovery contract that
``compile_definition`` validates against) and marks capabilities the shipped
hosts cannot provide; ``definition.md`` renders the published GradingDefinition
JSON Schema. Nothing is written by hand, so the pages cannot contradict the
compiler: ``--check`` fails when a contract changed without regeneration.
"""
import argparse
import json
from pathlib import Path

from autograder import EvaluationError, describe_templates, grading_definition_json_schema
from autograder.models.contracts.catalog import CAPABILITY_DESCRIPTIONS
from autograder.services.preparation import check_capabilities
from execution_host.docker import DockerHost

OUTPUT = Path(__file__).resolve().parents[1] / "docs" / "reference"
REGENERATE = "python scripts/generate_reference.py"
SHIPPED_HOSTS = "the HTTP API and the GitHub Action"
UNAVAILABLE = '!!! warning "Not available on the shipped hosts"'


def generated_notice(source):
    """The editor-facing marker at the top of each page."""
    return (f"<!-- Generated by scripts/generate_reference.py from {source}. Do not edit; "
            f"run `{REGENERATE}` after changing a contract. -->")


# --- JSON Schema to Markdown ---------------------------------------------------

def cell(text):
    """One table cell: a single line, pipes escaped, and ``<`` escaped outside code spans
    so a description mentioning ``<head>`` cannot inject HTML."""
    parts = " ".join(str(text).split()).replace("|", "\\|").split("`")
    return "`".join(part if index % 2 else part.replace("<", "&lt;") for index, part in enumerate(parts))


def code(value):
    """A JSON value as inline code."""
    return f"`{json.dumps(value, ensure_ascii=False)}`"


def type_of(schema, link):
    """Human-readable type of a JSON Schema; ``link`` names a ``$ref`` target."""
    if "$ref" in schema:
        return link(schema["$ref"].rsplit("/", 1)[-1])
    if "const" in schema:
        return code(schema["const"])
    if "enum" in schema:
        values = schema["enum"]
        return " or ".join(code(v) for v in values) if len(values) <= 6 else f"string (one of {len(values)} values)"
    for key in ("anyOf", "oneOf"):
        if key in schema:
            options = [type_of(option, link) for option in schema[key] if option.get("type") != "null"]
            nullable = len(options) < len(schema[key])
            return " or ".join(options) + (" or null" if nullable else "")
    kind = schema.get("type")
    if kind == "array":
        return f"list of {type_of(schema.get('items', {}), link)}"
    if kind == "object" and isinstance(schema.get("additionalProperties"), dict):
        keys = schema.get("propertyNames", {}).get("enum")
        key = " or ".join(f"`{k}`" for k in keys) if keys else "string"
        return f"map of {key} to {type_of(schema['additionalProperties'], link)}"
    return kind or "any JSON value"


BOUNDS = (("minLength", "length ≥ {}"), ("maxLength", "length ≤ {}"), ("minimum", "≥ {}"),
          ("maximum", "≤ {}"), ("exclusiveMinimum", "> {}"), ("exclusiveMaximum", "< {}"),
          ("minItems", "≥ {} items"), ("maxItems", "≤ {} items"),
          ("pattern", "matches `{}`"))


def constraints(schema):
    """Validation bounds of a property, including those of list items and map values."""
    parts = [template.format(schema[key]) for key, template in BOUNDS if key in schema]
    if schema.get("uniqueItems"):
        parts.append("unique items")
    if isinstance(schema.get("items"), dict):
        parts += [f"each item {part}" for part in constraints(schema["items"])]
    if isinstance(schema.get("additionalProperties"), dict):
        parts += [f"each value {part}" for part in constraints(schema["additionalProperties"])]
    for key in ("anyOf", "oneOf"):
        for option in schema.get(key, ()):
            parts += constraints(option)
    return parts


def property_rows(schema, link, label):
    """A table of an object schema's properties, in declaration order."""
    required = set(schema.get("required", []))
    rows = [f"| {label} | Type | Required | Default | Constraints | Description |",
            "| --- | --- | --- | --- | --- | --- |"]
    for name, prop in schema.get("properties", {}).items():
        is_required = name in required
        if is_required:
            default = "—"
        elif "$ref" in prop and isinstance(prop.get("default"), dict):
            default = "each field's default"
        else:
            default = code(prop["default"]) if "default" in prop else "none"
        rows.append(f"| `{name}` | {cell(type_of(prop, link))} | {'yes' if is_required else 'no'} | "
                    f"{cell(default)} | {cell('; '.join(constraints(prop)) or '—')} | "
                    f"{cell(prop.get('description', ''))} |")
    return rows


# --- Evaluator reference -------------------------------------------------------

def unavailable_capabilities(capabilities):
    """Capability -> the error a definition fails with on a host lacking it (core's own check)."""
    missing = {}
    for capability in CAPABILITY_DESCRIPTIONS:
        try:
            check_capabilities(frozenset({capability}), capabilities)
        except EvaluationError as error:
            missing[capability] = error.code
    return missing


def unavailable_warning(capabilities, missing):
    """The admonition shown where an evaluator or template cannot run on the shipped hosts."""
    names = ", ".join(f"`{c}`" for c in capabilities)
    codes = ", ".join(sorted({f"`{missing[c]}`" for c in capabilities}))
    return [UNAVAILABLE, f"    Requires {names}, which {SHIPPED_HOSTS} do not provide: a definition "
            f"using it fails with {codes} before any sandbox is acquired.", ""]


def example(identifier, parameters):
    """A criterion using the evaluator with its validated catalog sample parameters."""
    criterion = {"id": identifier.replace("_", "-"), "type": identifier,
                 "name": identifier.replace("_", " ").capitalize(), "parameters": parameters, "weight": 100}
    return ["```json", json.dumps(criterion, indent=2, ensure_ascii=False), "```"]


def render_evaluators(catalog, missing):
    """The evaluator reference: capabilities, then every template and its evaluators."""
    lines = ["# Evaluator reference", "", generated_notice("the evaluator contracts (`describe_templates()`)"), "",
             "Every evaluator a criterion `type` can name, with the parameters `compile_definition` accepts. "
             "List the evaluator's template in the definition's `templates`. The same data is served by "
             "`GET /api/v1/templates`; the [definition reference](definition.md) describes the rest of a "
             "definition.", "",
             "## Capabilities {#capabilities}", "",
             "An evaluator runs only on a host that provides its capabilities. The HTTP API composes "
             "`execution_host.docker.DockerHost`; the GitHub Action composes `execution_host.runner.RunnerHost`, "
             "which provides the same capabilities on the runner's Docker.", "",
             "| Capability | Shipped hosts | Meaning |", "| --- | --- | --- |"]
    for capability, meaning in catalog.capabilities.items():
        support = f"not provided (`{missing[capability]}`)" if capability in missing else "provided"
        lines.append(f"| `{capability}` | {support} | {cell(meaning)} |")
    lines.append("")
    for template in catalog.templates:
        lines += [f"## {template.name} (`{template.identifier}`) {{#{template.identifier}}}", "",
                  cell(template.description), ""]
        needs = [sorted(set(e.required_capabilities) & set(missing)) for e in template.evaluators]
        if template.evaluators and all(needs):
            lines += unavailable_warning(sorted({c for n in needs for c in n}), missing)
        lines += ["| Evaluator | Description |", "| --- | --- |"]
        lines += [f"| [`{e.identifier}`](#{e.identifier}) | {cell(e.description)} |" for e in template.evaluators]
        lines.append("")
        for evaluator in template.evaluators:
            lines += render_evaluator(template.identifier, evaluator, missing)
    return "\n".join(lines).rstrip("\n") + "\n"


def render_evaluator(template, evaluator, missing):
    """One evaluator: facts, availability, parameter table and example."""
    lines = [f"### `{evaluator.identifier}` {{#{evaluator.identifier}}}", "", cell(evaluator.description), ""]
    capabilities = ", ".join(f"`{c}`" for c in evaluator.required_capabilities) or "none"
    languages = ", ".join(f"`{lang}`" for lang in evaluator.supported_languages or []) or "any allowed language"
    lines += [f"- **Template:** `{template}`", f"- **Capabilities:** {capabilities}",
              f"- **Languages:** {languages}"]
    if evaluator.absence_check:
        lines.append(f"- **Passes when absent:** {cell(evaluator.absence_check)}")
    lines.append("")
    unavailable = [c for c in evaluator.required_capabilities if c in missing]
    if unavailable:
        lines += unavailable_warning(unavailable, missing)
    schema = evaluator.parameters_schema
    if schema.get("properties"):
        lines += property_rows(schema, lambda name: f"`{name}`", "Parameter")
    else:
        lines.append("No parameters: use `\"parameters\": {}`.")
    lines += ["", "Example criterion (placeholder values; defaults written out):", "", *example(evaluator.identifier, evaluator.sample_parameters), ""]
    return lines


# --- Definition reference ------------------------------------------------------

def definition_objects(schema):
    """Object definitions reachable from the root through properties, depth first, with
    every JSON path that reaches them. Evaluator parameter contracts are left to the
    evaluator reference; ``JsonValue`` and other property-less definitions are plain types."""
    defs = {"GradingDefinition": schema, **schema["$defs"]}
    order, paths = [], {"GradingDefinition": []}

    def visit(name):
        order.append(name)
        base = paths[name][0] + "." if paths[name] else ""
        for prop, value in defs[name].get("properties", {}).items():
            for target, suffix in refs(value):
                if target == name or "properties" not in defs[target]:
                    continue
                first = target not in paths
                paths.setdefault(target, []).append(f"{base}{prop}{suffix}")
                if first:
                    visit(target)

    visit("GradingDefinition")
    return [(name, defs[name], paths[name]) for name in order]


def refs(schema, suffix=""):
    """``($defs name, path suffix)`` for each reference inside a property schema."""
    if "$ref" in schema:
        yield schema["$ref"].rsplit("/", 1)[-1], suffix
    for key in ("anyOf", "oneOf"):
        for option in schema.get(key, ()):
            yield from refs(option, suffix)
    if isinstance(schema.get("items"), dict):
        yield from refs(schema["items"], suffix + "[]")
    if isinstance(schema.get("additionalProperties"), dict):
        key = "<language>" if schema.get("propertyNames", {}).get("enum") else "<key>"
        yield from refs(schema["additionalProperties"], f"{suffix}.{key}")


def render_definition(schema):
    """The definition reference: one section per object of the definition schema."""
    objects = definition_objects(schema)
    documented = {name for name, _, _ in objects}

    def link(name):
        return f"[{name}](#{name.lower()})" if name in documented else "any JSON value"

    lines = ["# Definition reference", "", generated_notice("the GradingDefinition JSON Schema"), "",
             "Every field of a grading definition, as the [v1 JSON Schema](../contracts/v1/grading-definition.schema.json) "
             "publishes it. Omitted optional fields take the default shown. Each criterion's `parameters` are "
             "described per evaluator in the [evaluator reference](evaluators.md); rules JSON Schema cannot "
             "express are in [DEFINITIONS.md](../contracts/DEFINITIONS.md).", ""]
    for name, value, paths in objects:
        where = ", ".join(f"`{path}`" for path in paths)
        lines += [f"## {name} {{#{name.lower()}}}", "", cell(value.get("description", "")), ""]
        lines += [f"Location: {where}", ""] if paths else []
        lines += [*property_rows(value, link, "Field"), ""]
    return "\n".join(lines).rstrip("\n") + "\n"


# --- Files ---------------------------------------------------------------------

def render_pages(templates=None):
    """``{file name: Markdown}``; ``templates`` adds trusted templates as in ``describe_templates``."""
    missing = unavailable_capabilities(DockerHost(mode="local").capabilities)
    return {"definition.md": render_definition(grading_definition_json_schema()),
            "evaluators.md": render_evaluators(describe_templates(templates), missing)}


def write_pages(directory, templates=None):
    """Write the rendered pages into ``directory``."""
    directory.mkdir(parents=True, exist_ok=True)
    for name, text in render_pages(templates).items():
        (directory / name).write_text(text, encoding="utf-8")


def stale_pages(directory, templates=None):
    """Pages under ``directory`` that are missing or differ from a fresh rendering."""
    return [directory / name for name, text in sorted(render_pages(templates).items())
            if not (directory / name).is_file() or (directory / name).read_text(encoding="utf-8") != text]


def main(argv=None):
    """Regenerate the pages, or with ``--check`` fail when any is stale."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if a generated page is stale")
    parser.add_argument("--output", type=Path, default=OUTPUT, help="directory of the pages")
    args = parser.parse_args(argv)
    if args.check:
        stale = stale_pages(args.output)
        if stale:
            parser.error(f"{', '.join(map(str, stale))} stale; run {REGENERATE}")
    else:
        write_pages(args.output)


if __name__ == "__main__":
    main()
